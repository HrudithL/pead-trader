"""
Re-run the base_unit_fraction / liquidity_cap_frac elbow sweep -- previously done in
scripts/19_param_sweep_extended.py on the pre-neutralization extreme/rank-weighted/balanced
signals -- specifically on Strategy 6's own sector+size-neutral, trim=0.15/tilt=1.0 book. That
older sweep predates size-neutrality, sector-neutrality, and priority-based leverage-cap
trimming; all three change how a given base_unit_fraction actually behaves (more diversified
positions per quarter, best convictions no longer diluted when a cap binds), so there's no reason
to assume the old elbow point still applies to this specific, more capital-efficient book.

Reuses positions_strategy6_v2.parquet (data/positions_strategy6_v2.parquet, regenerated by
scripts/24_finalize_strategy6.py from this project's own trim/tilt/size/sector-neutral weighting)
-- the per-position `weight` column there is independent of base_unit_fraction/liquidity_cap_frac
(those only enter at the notional-sizing step below), so it's safe to reuse across every grid
point rather than recomputing per point. The per-quarter sizing loop uses the SAME priority-based
leverage-cap trimming Strategy 6 actually uses (highest-conviction-first, not scripts/19's older
uniform proportional scale-down), at Strategy 6's own finalized MAX_GROSS_LEVERAGE=2.5x.

NOTE on this session's local pipeline regeneration: this worktree's raw WRDS-derived data doesn't
carry the exact intermediate decay-day-cell values the original repo generation produced (a
handful of thin holding-period cells are sensitive to floating-point/library-version differences
in a threshold-crossing algorithm -- see scripts/14 and /15). Regenerating the full pipeline
locally reproduces Strategy 6 to within about 0.2pp return / 0.03 Sharpe / 0.7pp max DD of the
tracked baseline (6.32%/0.99/-17.3% here vs. the tracked 6.49%/1.02/-16.6%) -- close enough that
the ELBOW this sweep finds should be trustworthy, but the exact operating-point number should be
read as "regenerated-book" rather than bit-identical to the tracked figure.

Output: data/sweep_strategy6_sizing.csv (every combination), printed frontier table.
"""
import pandas as pd
import numpy as np
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
RAW = Path("C:/Users/hrudi/Documents/BEI/PEAD_Trading/data/normalized_equity")

INITIAL_CAPITAL = 10_000_000.0
MAX_GROSS_LEVERAGE = 2.5  # Strategy 6's own finalized cap
COST_BPS = {1: 25, 2: 15, 3: 10, 4: 7, 5: 5}
DEFAULT_COST_BPS = 15

print("loading daily market-adjusted return panel...")
frames = []
for y in range(1995, 2015):
    frames.append(pd.read_parquet(RAW / f"equity_{y}.parquet", columns=["permno", "date", "ret"]))
eq = pd.concat(frames, ignore_index=True)
mkt = pd.read_parquet(RAW / "market_benchmark.parquet", columns=["date", "vwretd"])
eq = eq.merge(mkt, on="date", how="left")
eq["ret_mktadj"] = (eq["ret"] - eq["vwretd"]).fillna(0.0)
eq = eq.sort_values(["permno", "date"]).drop_duplicates(subset=["permno", "date"]).reset_index(drop=True)
eq_ret = eq["ret_mktadj"].to_numpy()
eq_date_arr = eq["date"].to_numpy()

calendar_dt = pd.DatetimeIndex(sorted(mkt["date"].unique()))
date_to_idx = {d: i for i, d in enumerate(calendar_dt)}
n_days = len(calendar_dt)
quarter_of = calendar_dt.to_period("Q")
unique_quarters = quarter_of.unique().sort_values()
n_quarters = len(unique_quarters)
quarter_code_map = {q: i for i, q in enumerate(unique_quarters)}
quarter_code_of_day = np.array([quarter_code_map[q] for q in quarter_of])

# ---------- one-time, parameter-independent expansion (same pattern as scripts/19) ----------
pos = pd.read_parquet(DATA / "positions_strategy6_v2.parquet").reset_index(drop=True)
pos["day0_date"] = pd.to_datetime(pos["day0_date"])
pos["exit_date"] = pd.to_datetime(pos["exit_date"])
n_pos = len(pos)
print(f"Strategy 6 book: {n_pos:,} active positions (weight != 0, trim=0.15/tilt=1.0/sector+size-neutral)")

entry_qcode = pos["day0_date"].dt.to_period("Q").map(quarter_code_map).to_numpy()
exit_qcode = pos["exit_date"].dt.to_period("Q").map(quarter_code_map).to_numpy()
weight = pos["weight"].to_numpy()
liq_q = pos["liquidity_quintile"] if "liquidity_quintile" in pos.columns else pd.Series(np.nan, index=pos.index)
cost_bps = liq_q.map(COST_BPS).fillna(DEFAULT_COST_BPS).to_numpy()
adv21 = pos["avg_dollar_volume_21d"].to_numpy() if "avg_dollar_volume_21d" in pos.columns else np.full(n_pos, np.inf)

entry_cal_idx = pos["day0_date"].map(date_to_idx).to_numpy()
exit_cal_idx = pos["exit_date"].map(date_to_idx).to_numpy()

entry_idx = pos["entry_row_idx"].to_numpy()
exit_idx = pos["exit_row_idx"].to_numpy()
lengths = exit_idx - entry_idx
total_rows = int(lengths.sum())
starts = entry_idx + 1
rep_pos_idx = np.repeat(np.arange(n_pos), lengths)
offsets = np.arange(total_rows) - np.repeat(np.cumsum(lengths) - lengths, lengths)
flat_eq_row = np.repeat(starts, lengths) + offsets
flat_ret = eq_ret[flat_eq_row]
flat_date = eq_date_arr[flat_eq_row]
flat_cal_idx = calendar_dt.searchsorted(flat_date)
flat_qcode = quarter_code_of_day[flat_cal_idx]

order = np.argsort(flat_qcode, kind="stable")
flat_qcode_sorted = flat_qcode[order]
flat_ret_sorted = flat_ret[order]
rep_pos_idx_sorted = rep_pos_idx[order]
boundaries = np.searchsorted(flat_qcode_sorted, np.arange(n_quarters + 1))


def simulate(base_unit_fraction, liquidity_cap_frac, max_gross_leverage=MAX_GROSS_LEVERAGE):
    """Same priority-based (highest-conviction-first) leverage-cap trimming Strategy 6 itself
    uses (scripts/24), swept over base_unit_fraction / liquidity_cap_frac."""
    liq_cap_dollars = np.where(np.isfinite(adv21), liquidity_cap_frac * adv21, np.inf)
    trailing_nav = INITIAL_CAPITAL
    notional = np.zeros(n_pos)
    base_unit_at_entry = np.zeros(n_pos)
    n_capped_quarters = 0

    for qi in range(n_quarters):
        q_mask = entry_qcode == qi
        base_unit = trailing_nav * base_unit_fraction
        if q_mask.any():
            idx = np.where(q_mask)[0]
            target = weight[idx] * base_unit
            cap = liq_cap_dollars[idx]
            target = np.sign(target) * np.minimum(np.abs(target), cap)
            gross_requested = float(np.abs(target).sum())
            max_gross = max_gross_leverage * trailing_nav
            q_notional = target.copy()
            if gross_requested > max_gross and gross_requested > 0:
                n_capped_quarters += 1
                order_priority = np.argsort(-np.abs(target))
                cum = np.cumsum(np.abs(target[order_priority]))
                keep_mask = cum <= max_gross
                q_notional = np.zeros_like(target)
                q_notional[order_priority[keep_mask]] = target[order_priority[keep_mask]]
                n_kept = keep_mask.sum()
                if n_kept < len(target):
                    remaining = max_gross - (cum[n_kept - 1] if n_kept > 0 else 0.0)
                    boundary = order_priority[n_kept]
                    if remaining > 0:
                        q_notional[boundary] = np.sign(target[boundary]) * min(abs(target[boundary]), remaining)
            notional[idx] = q_notional
            base_unit_at_entry[idx] = base_unit

        s, e = boundaries[qi], boundaries[qi + 1]
        trade_pnl_q = float(np.sum(notional[rep_pos_idx_sorted[s:e]] * flat_ret_sorted[s:e])) if e > s else 0.0
        entry_cost_q = float(np.sum(np.abs(notional[q_mask]) * cost_bps[q_mask] / 10_000.0)) if q_mask.any() else 0.0
        exit_mask = exit_qcode == qi
        exit_cost_q = float(np.sum(np.abs(notional[exit_mask]) * cost_bps[exit_mask] / 10_000.0)) if exit_mask.any() else 0.0
        trailing_nav += trade_pnl_q - entry_cost_q - exit_cost_q

    entry_costs = np.abs(notional) * (cost_bps / 10_000.0)
    exit_costs = entry_costs.copy()
    daily_pnl = np.zeros(n_days)
    np.add.at(daily_pnl, entry_cal_idx, -entry_costs)
    np.add.at(daily_pnl, exit_cal_idx, -exit_costs)
    flat_notional = notional[rep_pos_idx]
    gross_pnl_from_trading = float(np.sum(flat_notional * flat_ret))
    np.add.at(daily_pnl, flat_cal_idx, flat_notional * flat_ret)

    exposure_delta = np.zeros(n_days + 1)
    np.add.at(exposure_delta, entry_cal_idx, np.abs(notional))
    np.add.at(exposure_delta, exit_cal_idx, -np.abs(notional))
    gross_exposure = np.cumsum(exposure_delta[:n_days])

    nav = INITIAL_CAPITAL + np.cumsum(daily_pnl)
    daily_ret = np.diff(nav, prepend=INITIAL_CAPITAL) / INITIAL_CAPITAL
    years = n_days / 252.0
    total_ret = (nav[-1] - INITIAL_CAPITAL) / INITIAL_CAPITAL
    ann_ret = (1 + total_ret) ** (1 / years) - 1
    ann_vol = daily_ret.std(ddof=1) * np.sqrt(252)
    sharpe = (daily_ret.mean() * 252) / ann_vol if ann_vol > 0 else np.nan
    running_max = np.maximum.accumulate(nav)
    max_dd = ((nav - running_max) / running_max).min()
    liquidity_capped = (np.abs(weight * base_unit_at_entry) > np.abs(notional) + 1e-6) & (base_unit_at_entry > 0)
    total_costs = entry_costs.sum() + exit_costs.sum()

    return dict(
        base_unit_fraction=base_unit_fraction, liquidity_cap_frac=liquidity_cap_frac,
        annualized_return=ann_ret, annualized_vol=ann_vol, sharpe=sharpe, max_drawdown=max_dd,
        avg_leverage=float(gross_exposure.mean() / INITIAL_CAPITAL),
        pct_leverage_capped_quarters=float(n_capped_quarters / n_quarters),
        pct_liquidity_capped=float(liquidity_capped.mean()),
        total_transaction_costs=float(total_costs),
        cost_pct_of_gross_pnl=float(total_costs / gross_pnl_from_trading) if gross_pnl_from_trading > 0 else np.nan,
        final_nav=float(nav[-1]),
    )


# same grid shape as scripts/19_param_sweep_extended.py's sweep_extended.csv, for direct
# comparability, extended a bit further given Strategy 6's book is more capital-efficient
buf_grid = [0.001, 0.0015, 0.002, 0.003, 0.004, 0.005, 0.0075, 0.010, 0.015, 0.020, 0.030, 0.050]
liq_settings = [0.01, 0.05, 0.10]

rows = []
for lf in liq_settings:
    for buf in buf_grid:
        rows.append(simulate(buf, lf))

sweep = pd.DataFrame(rows)
sweep.to_csv(DATA / "sweep_strategy6_sizing.csv", index=False)

pd.set_option("display.width", 160)
for lf in liq_settings:
    sub = sweep[sweep.liquidity_cap_frac == lf]
    print(f"\n-- liquidity_cap_frac={lf} --")
    print(sub[["base_unit_fraction", "annualized_return", "annualized_vol", "sharpe",
               "max_drawdown", "avg_leverage", "pct_leverage_capped_quarters",
               "pct_liquidity_capped", "cost_pct_of_gross_pnl"]].to_string(index=False))

# current operating point, for reference
current = sweep[(sweep.base_unit_fraction == 0.003) & (sweep.liquidity_cap_frac == 0.05)]
print("\ncurrent operating point (buf=0.003, liq_cap=0.05):")
print(current.to_string(index=False))
print("\nwrote data/sweep_strategy6_sizing.csv")
